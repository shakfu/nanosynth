#!/usr/bin/env python3
"""Regenerate the input-rate rules that nanosynth enforces at SynthDef build.

Runs scripts/sclang_input_rates.scd under sclang 3.14.1 with the sc3-plugins
classes, writes spec/sclang-input-rates.json and src/nanosynth/_input_rates.py.

Usage::

    SCLANG=/path/to/sclang SC_CLASSLIB=/path/to/SCClassLibrary \\
    SC3_PLUGINS=/path/to/sc3-plugins/source python scripts/sclang_input_rates.py

The defaults match scripts/superdirt_oracle.py setup.
"""

from __future__ import annotations

import json
import os
import pprint
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(os.environ.get("NANODIRT_CACHE", Path.home() / ".cache" / "nanodirt"))
SCRIPT = ROOT / "scripts" / "sclang_input_rates.scd"
SPEC = ROOT / "spec" / "sclang-input-rates.json"
MODULE = ROOT / "src" / "nanosynth" / "_input_rates.py"
TOKENS = {"audio": "ar", "control": "kr", "scalar": "ir"}


def main() -> int:
    sclang = os.environ.get("SCLANG", CACHE / "src" / "scbuild" / "lang" / "sclang")
    classlib = Path(os.environ.get("SC_CLASSLIB", CACHE / "src" / "sc" / "SCClassLibrary"))
    plugins = Path(os.environ.get("SC3_PLUGINS", CACHE / "src" / "sc3-plugins" / "source"))
    with tempfile.TemporaryDirectory() as tmp:
        conf = Path(tmp) / "sclang_conf.yaml"
        conf.write_text(
            f"includePaths:\n  - {classlib}\n  - {plugins}\n"
            f"excludePaths:\n  - {classlib / 'scide_scqt'}\n"
            "excludeDefaultPaths: true\npostInlineWarnings: false\n"
        )
        raw = Path(tmp) / "rates.json"
        subprocess.run(
            [str(sclang), "-l", str(conf), str(SCRIPT), str(raw)],
            check=True,
            timeout=600,
            stdin=subprocess.PIPE,
            stdout=subprocess.DEVNULL,
        )
        data = json.loads(raw.read_text())
    SPEC.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")
    # class -> rate token -> slot -> allowed rate tokens
    rules: dict[str, dict[str, dict[int, tuple[str, ...]]]] = {}
    for name, methods in sorted(data["ugens"].items()):
        for sel, rec in sorted(methods.items()):
            if rec["slots"]:
                rules.setdefault(name, {})[TOKENS[rec["rate"]]] = {
                    int(i): tuple(TOKENS[r] for r in allowed)
                    for i, allowed in sorted(rec["slots"].items(), key=lambda kv: int(kv[0]))
                }
    MODULE.write_text(
        '"""Input rates sclang\'s checkInputs accepts, by UGen class, rate and input slot.\n\n'
        "Generated by scripts/sclang_input_rates.py from sclang "
        f"{data['sclang_version']}; do not edit.\n"
        '"""\n\n'
        f"RULES: dict[str, dict[str, dict[int, tuple[str, ...]]]] = {pprint.pformat(rules, width=100, compact=True)}\n"
    )
    subprocess.run([shutil.which("ruff") or "ruff", "format", "-q", str(MODULE)], check=True)
    print(f"Wrote {SPEC} and {MODULE} ({len(rules)} classes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
